package model

import (
	"encoding/json"
	"time"
)

// WorkflowInstanceRecord represents a workflow instance (run) record in the database
type WorkflowInstanceRecord struct {
	ID                   string                 `json:"id"`
	WorkflowDefinitionID string                 `json:"workflow_definition_id"`
	WorkflowVersion      int                    `json:"workflow_version"`
	Status               WorkflowInstanceStatus `json:"status"`
	Input                json.RawMessage        `json:"input,omitempty"`
	CreatedAt            time.Time              `json:"created_at"`
	UpdatedAt            time.Time              `json:"updated_at"`
	CompletedAt          *time.Time             `json:"completed_at,omitempty"`
}

// WorkflowInstanceStatusResponse represents the status of a workflow instance with task counts
type WorkflowInstanceStatusResponse struct {
	ID             string                 `json:"id"`
	Status         WorkflowInstanceStatus `json:"status"`
	PendingTasks   int                    `json:"pending_tasks"`
	RunningTasks   int                    `json:"running_tasks"`
	CompletedTasks int                    `json:"completed_tasks"`
	FailedTasks    int                    `json:"failed_tasks"`
	TotalTasks     int                    `json:"total_tasks"`
	CreatedAt      time.Time              `json:"created_at"`
	UpdatedAt      time.Time              `json:"updated_at"`
}

// StartWorkflowRequest represents a request to start a workflow execution
// RunID is optional - if not provided, it will be generated by the backend
type StartWorkflowRequest struct {
	RunID            string          `json:"run_id,omitempty"`
	WorkflowID       string          `json:"workflow_id"`
	WorkflowVersion  int             `json:"workflow_version"`
	Input            json.RawMessage `json:"input,omitempty"`
	StartedBy        string          `json:"started_by,omitempty"`
	ExecutionOptions json.RawMessage `json:"execution_options,omitempty"`
	StartNodeID      string          `json:"start_node_id,omitempty"`
	StartedAtUnixMs  int64           `json:"started_at_unix_ms,omitempty"`
}

// TaskInstanceRecord represents a task instance record in the database
type TaskInstanceRecord struct {
	ID             string             `json:"id"`
	RunID          string             `json:"run_id"`
	NodeID         string             `json:"node_id"`
	NodeType       string             `json:"node_type"`
	State          TaskInstanceStatus `json:"state"`
	Attempt        int                `json:"attempt"`
	Input          json.RawMessage    `json:"input,omitempty"`
	Output         json.RawMessage    `json:"output,omitempty"`
	LastError      json.RawMessage    `json:"last_error,omitempty"`
	ScheduledAt    *time.Time         `json:"scheduled_at,omitempty"`
	StartedAt      *time.Time         `json:"started_at,omitempty"`
	FinishedAt     *time.Time         `json:"finished_at,omitempty"`
	CompletedAt    *time.Time         `json:"completed_at,omitempty"`
	CreatedAt      time.Time          `json:"created_at"`
	UpdatedAt      time.Time          `json:"updated_at"`
	LeaseOwner     *string            `json:"lease_owner,omitempty"`
	LeaseExpiresAt *time.Time         `json:"lease_expires_at,omitempty"`
}

// ExecutionDetailResponse represents comprehensive execution details
type ExecutionDetailResponse struct {
	Execution     *WorkflowInstanceRecord `json:"execution"`
	Context       *RunContext             `json:"context,omitempty"`
	TaskInstances []TaskInstanceRecord    `json:"task_instances"`
}
